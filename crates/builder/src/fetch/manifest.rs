//! `inputs/manifest.toml`: one entry per fetched file, with its provenance and license.
//!
//! This is the seed of the pack attribution file and of the license filter (roadmap §7).

use std::collections::BTreeMap;
use std::path::Path;

use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};

#[derive(Debug, Default, Serialize, Deserialize)]
pub struct Manifest {
    #[serde(default, rename = "file")]
    pub files: Vec<FileEntry>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct FileEntry {
    /// Relative to the manifest's directory, with `/` separators.
    pub path: String,
    /// `osm`, `openaddresses`, `tiger`, `oda` or `nar`.
    pub source: String,
    /// Finer-grained id within the source, e.g. an OpenAddresses `source/layer-name`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_id: Option<String>,
    pub url: String,
    /// Where the license was read from, when it is not fixed per source.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub metadata_url: Option<String>,
    /// UTC, RFC 3339.
    pub downloaded: String,
    pub size: u64,
    pub sha256: String,
    /// Only for sources that publish an MD5 (Geofabrik); it was verified on download.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub md5: Option<String>,
    pub license: License,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct License {
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub url: Option<String>,
    /// `None` when the source metadata does not say.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub attribution_required: Option<bool>,
    /// Text to show in the pack's attribution screen.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub attribution: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub share_alike: Option<bool>,
}

impl Manifest {
    pub fn load_or_default(path: &Path) -> Result<Self> {
        match std::fs::read_to_string(path) {
            Ok(text) => toml::from_str(&text).with_context(|| format!("parse {}", path.display())),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Self::default()),
            Err(e) => Err(e).with_context(|| format!("read {}", path.display())),
        }
    }

    /// Writes entries sorted by path, via a temp file so a crash never leaves half a manifest.
    pub fn save(&self, path: &Path) -> Result<()> {
        let text = format!(
            "# Generated by `omp-builder fetch`. Paths are relative to this file.\n\n{}",
            toml::to_string(self)?
        );
        let tmp = path.with_extension("toml.tmp");
        std::fs::write(&tmp, text).with_context(|| format!("write {}", tmp.display()))?;
        std::fs::rename(&tmp, path).with_context(|| format!("rename to {}", path.display()))
    }

    pub fn get(&self, path: &str) -> Option<&FileEntry> {
        self.files.iter().find(|f| f.path == path)
    }

    pub fn upsert(&mut self, entries: impl IntoIterator<Item = FileEntry>) {
        let mut by_path: BTreeMap<String, FileEntry> = std::mem::take(&mut self.files)
            .into_iter()
            .map(|f| (f.path.clone(), f))
            .collect();
        for e in entries {
            by_path.insert(e.path.clone(), e);
        }
        self.files = by_path.into_values().collect();
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(path: &str, size: u64) -> FileEntry {
        FileEntry {
            path: path.into(),
            source: "osm".into(),
            source_id: None,
            url: format!("https://example.com/{path}"),
            metadata_url: None,
            downloaded: "2026-10-23T00:00:00Z".into(),
            size,
            sha256: "00".into(),
            md5: Some("11".into()),
            license: License {
                name: "ODbL-1.0".into(),
                url: None,
                attribution_required: Some(true),
                attribution: Some("© OpenStreetMap contributors".into()),
                share_alike: Some(true),
            },
        }
    }

    #[test]
    fn upsert_replaces_and_sorts() {
        let mut m = Manifest::default();
        m.upsert([entry("b", 1), entry("a", 1)]);
        m.upsert([entry("b", 2)]);
        let paths: Vec<_> = m.files.iter().map(|f| f.path.as_str()).collect();
        assert_eq!(paths, ["a", "b"]);
        assert_eq!(m.get("b").unwrap().size, 2);
    }

    #[test]
    fn toml_round_trip() {
        let mut m = Manifest::default();
        m.upsert([entry("osm/x.osm.pbf", 5)]);
        let back: Manifest = toml::from_str(&toml::to_string(&m).unwrap()).unwrap();
        assert_eq!(back.files, m.files);
    }
}
